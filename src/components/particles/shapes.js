function buildNeuralNetTopology() {
  const layerSizes = [5, 5, 5, 5, 3];
  const xs = [-1.1, -0.55, 0, 0.55, 1.1];
  const nodes = [];
  const edges = [];
  const nodeWeight = [];
  const layerNodeIdx = [];

  let idx = 0;
  for (let L = 0; L < layerSizes.length; L++) {
    const n = layerSizes[L];
    const layer = [];
    for (let i = 0; i < n; i++) {
      const y = n === 1 ? 0 : (i / (n - 1)) * 1.35 - 0.675;
      nodes.push([xs[L], y, 0]);
      const w = L === 0 || L === layerSizes.length - 1 ? 1 : 2;
      nodeWeight.push(w);
      layer.push(idx++);
    }
    layerNodeIdx.push(layer);
  }

  for (let L = 0; L < layerNodeIdx.length - 1; L++) {
    for (const a of layerNodeIdx[L]) {
      for (const b of layerNodeIdx[L + 1]) {
        edges.push([a, b]);
      }
    }
  }

  return { nodes, edges, nodeWeight };
}

function buildNetworkPoints(count) {
  const { nodes, edges, nodeWeight } = buildNeuralNetTopology();
  return buildTopologyPoints({
    nodes,
    edges,
    count,
    nodeWeight,
    z: 0,
    nodeFraction: 0.28,
  });
}


