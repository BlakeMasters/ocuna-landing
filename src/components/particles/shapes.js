function sampleEdges(geometry, targetCount, scale = 1) {
  const edges = new THREE.EdgesGeometry(geometry);
  const pos = edges.attributes.position;
  const segments = [];

  for (let i = 0; i < pos.count; i += 2) {
    const ax = pos.getX(i) * scale;
    const ay = pos.getY(i) * scale;
    const az = pos.getZ(i) * scale;
    const bx = pos.getX(i + 1) * scale;
    const by = pos.getY(i + 1) * scale;
    const bz = pos.getZ(i + 1) * scale;
    const len = Math.hypot(bx - ax, by - ay, bz - az);
    if (len > 0.001) {
      segments.push({ ax, ay, az, bx, by, bz, len });
    }
  }

  edges.dispose();
  geometry.dispose();

  const totalLen = segments.reduce((sum, s) => sum + s.len, 0);
  const points = [];
  let remaining = targetCount;

  for (let i = 0; i < segments.length; i++) {
    const seg = segments[i];
    const count =
      i === segments.length - 1
        ? remaining
        : Math.max(1, Math.round((seg.len / totalLen) * targetCount));
    remaining -= count;

    for (let j = 0; j < count; j++) {
      const t = count === 1 ? 0.5 : j / (count - 1);
      points.push(
        seg.ax + (seg.bx - seg.ax) * t,
        seg.ay + (seg.by - seg.ay) * t,
        seg.az + (seg.bz - seg.az) * t
      );
    }
  }

  return new Float32Array(points);
}

function samplePolyline(points3d, targetCount, closed = false) {
  const segments = [];
  const limit = closed ? points3d.length : points3d.length - 1;

  for (let i = 0; i < limit; i++) {
    const a = points3d[i];
    const b = points3d[(i + 1) % points3d.length];
    const len = Math.hypot(b[0] - a[0], b[1] - a[1], b[2] - a[2]);
    if (len > 0.001) {
      segments.push({ a, b, len });
    }
  }

  const totalLen = segments.reduce((sum, s) => sum + s.len, 0);
  const out = [];
  let remaining = targetCount;

  for (let i = 0; i < segments.length; i++) {
    const seg = segments[i];
    const count =
      i === segments.length - 1
        ? remaining
        : Math.max(1, Math.round((seg.len / totalLen) * targetCount));
    remaining -= count;

    for (let j = 0; j < count; j++) {
      const t = count === 1 ? 0.5 : j / (count - 1);
      out.push(
        seg.a[0] + (seg.b[0] - seg.a[0]) * t,
        seg.a[1] + (seg.b[1] - seg.a[1]) * t,
        seg.a[2] + (seg.b[2] - seg.a[2]) * t
      );
    }
  }

  return new Float32Array(out);
}

function buildTopologyPoints({
  nodes,
  edges,
  count,
  nodeWeight = [],
  z = 0,
  nodeFraction = 0.22,
}) {
  const nodes3d = nodes.map(([x, y]) => [x, y, z]);
  const weights =
    nodeWeight.length === nodes.length ? nodeWeight : nodes.map(() => 1);
  const totalWeight = weights.reduce((sum, w) => sum + w, 0) || 1;

  const nodeBudget = Math.max(
    nodes.length,
    Math.min(count - edges.length, Math.floor(count * nodeFraction))
  );
  const edgeBudget = Math.max(1, count - nodeBudget);

  const edgeSegments = edges.map(([a, b]) => {
    const n0 = nodes3d[a];
    const n1 = nodes3d[b];
    const len = Math.hypot(n1[0] - n0[0], n1[1] - n0[1], n1[2] - n0[2]);
    return { a: n0, b: n1, len: Math.max(len, 0.001) };
  });

  const totalEdgeLen = edgeSegments.reduce((sum, seg) => sum + seg.len, 0);
  const edgeParts = [];
  let edgeRemaining = edgeBudget;

  for (let i = 0; i < edgeSegments.length; i++) {
    const seg = edgeSegments[i];
    const segCount =
      i === edgeSegments.length - 1
        ? edgeRemaining
        : Math.max(1, Math.round((seg.len / totalEdgeLen) * edgeBudget));
    edgeRemaining -= segCount;
    edgeParts.push(sampleLine3D(seg.a, seg.b, segCount));
  }

  const nodePoints = [];
  for (let i = 0; i < nodeBudget; i++) {
    const t = (i + 0.5) / nodeBudget;
    let acc = 0;
    let nodeIdx = 0;
    for (let j = 0; j < weights.length; j++) {
      acc += weights[j] / totalWeight;
      if (t <= acc) {
        nodeIdx = j;
        break;
      }
    }
    const n = nodes3d[nodeIdx];
    const angle = i * 2.399963;
    const jitter = 0.018 + (weights[nodeIdx] / Math.max(...weights)) * 0.012;
    nodePoints.push(
      n[0] + Math.cos(angle) * jitter,
      n[1] + Math.sin(angle) * jitter,
      n[2]
    );
  }

  const edgeLen = edgeParts.reduce((sum, part) => sum + part.length, 0);
  const combined = new Float32Array(edgeLen + nodePoints.length);
  let offset = 0;
  for (const part of edgeParts) {
    combined.set(part, offset);
    offset += part.length;
  }
  for (let i = 0; i < nodePoints.length; i += 3) {
    combined[offset++] = nodePoints[i];
    combined[offset++] = nodePoints[i + 1];
    combined[offset++] = nodePoints[i + 2];
  }
  return combined;
}

