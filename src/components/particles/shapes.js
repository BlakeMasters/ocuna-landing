function buildDeploymentPoints(count) {
  const boxes = [
    { w: 0.5, h: 0.35, d: 0.5, y: -0.55 },
    { w: 0.65, h: 0.4, d: 0.65, y: -0.1 },
    { w: 0.35, h: 0.7, d: 0.35, y: 0.45 },
  ];
  const perBox = Math.floor(count / boxes.length);
  const parts = boxes.map((box, i) => {
    const geo = new THREE.BoxGeometry(box.w, box.h, box.d);
    const pts = sampleEdges(geo, i === boxes.length - 1 ? count - perBox * 2 : perBox, 1);
    for (let j = 1; j < pts.length; j += 3) {
      pts[j] += box.y;
    }
    return pts;
  });

  const total = parts.reduce((sum, p) => sum + p.length, 0);
  const out = new Float32Array(total);
  let offset = 0;
  for (const part of parts) {
    out.set(part, offset);
    offset += part.length;
  }
  return out;
}

function spherePoint(theta, phi, radius) {
  const sinPhi = Math.sin(phi);
  return [
    radius * sinPhi * Math.cos(theta),
    radius * Math.cos(phi),
    radius * sinPhi * Math.sin(theta),
  ];
}

function buildMeridianPath(theta, radius, steps) {
  const path = [];
  for (let i = 0; i <= steps; i++) {
    const phi = (i / steps) * Math.PI;
    path.push(spherePoint(theta, phi, radius));
  }
  return path;
}

function buildParallelPath(phi, radius, steps) {
  const path = [];
  for (let i = 0; i <= steps; i++) {
    const theta = (i / steps) * Math.PI * 2;
    path.push(spherePoint(theta, phi, radius));
  }
  return path;
}

function sampleLine3D(a, b, count) {
  const out = [];
  for (let i = 0; i < count; i++) {
    const t = count === 1 ? 0.5 : i / (count - 1);
    out.push(
      a[0] + (b[0] - a[0]) * t,
      a[1] + (b[1] - a[1]) * t,
      a[2] + (b[2] - a[2]) * t
    );
  }
  return new Float32Array(out);
}

function sampleMultiPolyline(paths, targetCount, closedFlags = []) {
  const segments = [];

  paths.forEach((path, pathIndex) => {
    const closed = closedFlags[pathIndex] ?? false;
    const limit = closed ? path.length : path.length - 1;

    for (let i = 0; i < limit; i++) {
      const a = path[i];
      const b = path[(i + 1) % path.length];
      const len = Math.hypot(b[0] - a[0], b[1] - a[1], b[2] - a[2]);
      if (len > 0.001) {
        segments.push({ a, b, len });
      }
    }
  });

  const totalLen = segments.reduce((sum, s) => sum + s.len, 0);
  const out = [];
  let remaining = targetCount;

  for (let i = 0; i < segments.length; i++) {
    const seg = segments[i];
    const count =
      i === segments.length - 1
        ? remaining
        : Math.max(1, Math.round((seg.len / totalLen) * targetCount));
    remaining -= count;

    for (let j = 0; j < count; j++) {
      const t = count === 1 ? 0.5 : j / (count - 1);
      out.push(
        seg.a[0] + (seg.b[0] - seg.a[0]) * t,
        seg.a[1] + (seg.b[1] - seg.a[1]) * t,
        seg.a[2] + (seg.b[2] - seg.a[2]) * t
      );
    }
  }

  return new Float32Array(out);
}

function buildHadamardBlochPoints(count) {
  const radius = 0.72;
  const nodeCount = Math.round(count * 0.24);
  const edgeCount = Math.max(1, count - nodeCount);
  const meridians = 3;
  const parallels = 3;
  const paths = [];

  for (let m = 0; m < meridians; m++) {
    paths.push(buildMeridianPath((m / meridians) * Math.PI, radius, 16));
  }
  for (let p = 1; p < parallels; p++) {
    paths.push(buildParallelPath((p / parallels) * Math.PI, radius, 20));
  }

  const nodes = [
    [0, radius, 0],
    [0, -radius, 0],
    [radius, 0, 0],
    [-radius, 0, 0],
    [0, 0, radius],
    [0, 0, -radius],
  ];
  const links = [
    [0, 2],
    [0, 3],
    [0, 4],
    [0, 5],
    [1, 2],
    [1, 3],
    [1, 4],
    [1, 5],
  ];
  links.forEach(([a, b]) => paths.push([nodes[a], nodes[b]]));

  const edgePoints = sampleMultiPolyline(
    paths,
    edgeCount,
    paths.map(() => false)
  );
  const nodePoints = [];
  for (let i = 0; i < nodeCount; i++) {
    const n = nodes[i % nodes.length];
    nodePoints.push(n[0], n[1], n[2]);
  }

  const combined = new Float32Array(edgePoints.length + nodePoints.length);
  combined.set(edgePoints, 0);
  combined.set(nodePoints, edgePoints.length);
  return combined;
}

