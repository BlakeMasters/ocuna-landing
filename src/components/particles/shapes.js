const shapeCache = new Map();

export const SHAPE_DETAIL_COUNT = 640;

export function sampleShapePoints(key, count) {
  const cacheKey = `${key}:${count}`;
  if (shapeCache.has(cacheKey)) {
    return shapeCache.get(cacheKey);
  }

  const builder = shapeBuilders[key];
  if (!builder) {
    return sampleEdges(new THREE.BoxGeometry(1, 1, 1), count, 1);
  }

  const points = builder(count);
  shapeCache.set(cacheKey, points);
  return points;
}
